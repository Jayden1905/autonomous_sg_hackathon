"""The semantic model as code. `semantic/model.yaml` + `semantic/schema.yaml` load into one SemanticModel.

Field names follow the ACM semantic engine so the two stay recognisable side by side.
One addition: `domain` on concepts, rules, metrics and passages, so a briefing can be
sliced per agent (atc | pilot | ground | shared).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal, Optional

import yaml
from pydantic import BaseModel, Field

Confidence = Literal["confirmed", "proposed", "rejected"]
Domain = Literal["atc", "pilot", "ground", "shared"]

SEMANTIC_DIR = Path(__file__).resolve().parent.parent.parent / "semantic"


class Evidence(BaseModel):
    """Why an element exists / was decided the way it was."""

    by: str  # profiler | brief | regulation | user | derived | research
    what: str  # one line, human-readable
    ref: str = ""  # passage id, table.column, URL
    confidence: Optional[float] = None


# ─── schema layer (generated by profiler.py) ─────────────────────────────────────────────────────

class Column(BaseModel):
    name: str
    type: Literal["int", "float", "str", "empty"]
    nulls: float = 0.0  # null ratio
    distinct: int = 0
    samples: list[str] = Field(default_factory=list)
    min: Optional[float] = None
    max: Optional[float] = None
    is_id: bool = False
    is_time: bool = False  # HHMM clock columns in this dataset


class Table(BaseModel):
    name: str
    path: str
    rows: int
    columns: list[Column]
    profiled_rows: int  # how many rows the profile read (may sample)
    evidence: list[Evidence] = Field(default_factory=list)


# ─── ontology layer (curated) ────────────────────────────────────────────────────────────────────

class Concept(BaseModel):
    """A box in the reference ontology. Entity types declare which concept they are."""

    name: str
    extends: Optional[str] = None
    abstract: bool = False
    definition: str = ""
    aliases: list[str] = Field(default_factory=list)
    domain: Domain = "shared"


class EntityType(BaseModel):
    """A concept as it exists in *this* dataset / scenario, bound to columns or marked synthetic."""

    name: str
    concept: str
    description: str = ""
    aliases: list[str] = Field(default_factory=list)
    table: Optional[str] = None
    id_column: Optional[str] = None
    name_column: Optional[str] = None
    attribute_columns: list[str] = Field(default_factory=list)
    synthetic: bool = False  # generated by data.py, not in the organisers' data
    scenario_field: Optional[str] = None  # where it lives on schemas.Scenario
    domain: Domain = "shared"
    evidence: list[Evidence] = Field(default_factory=list)
    status: Confidence = "confirmed"


class RelationType(BaseModel):
    name: str
    source_type: str
    target_type: str
    description: str = ""
    via: Optional[str] = None  # table.column that carries it, or scenario field
    cardinality: Literal["many_to_one", "one_to_one", "one_to_many", "many_to_many"] = "many_to_one"
    evidence: list[Evidence] = Field(default_factory=list)
    status: Confidence = "confirmed"


class Metric(BaseModel):
    name: str
    description: str = ""
    unit: str = ""
    grain: list[str] = Field(default_factory=list)  # entity types
    formula: str = ""  # human formula
    inputs: list[str] = Field(default_factory=list)  # table.column or scenario fields
    range_lo: Optional[float] = None
    range_hi: Optional[float] = None
    domain: Domain = "shared"
    evidence: list[Evidence] = Field(default_factory=list)
    status: Confidence = "confirmed"


class Rule(BaseModel):
    """Operational knowledge no table holds. `id` is what rules.py cites in every RuleResult.

    kind: threshold   a numeric limit        params: {op, value, unit} or a table
          constraint  a yes/no condition
          precedence  ordering / priority
          protocol    how the negotiation itself must run (from the brief)
    """

    id: str
    kind: Literal["threshold", "constraint", "precedence", "protocol"]
    text: str
    domain: Domain
    hard: Optional[bool] = None  # None for protocol rules
    subjects: list[str] = Field(default_factory=list)  # entity types / metrics
    params: dict[str, Any] = Field(default_factory=dict)
    source: str = ""  # passage id
    enforced_by: Optional[str] = None  # python symbol, e.g. rules.atc_rules
    evidence: list[Evidence] = Field(default_factory=list)
    status: Confidence = "confirmed"


class CodeEntry(BaseModel):
    label: str
    definition: str = ""
    aliases: list[str] = Field(default_factory=list)


class CodeSet(BaseModel):
    """What each raw coded value means. Agents read labels/definitions, never guess."""

    name: str
    description: str = ""
    column: Optional[str] = None  # table.column, or scenario field
    entries: dict[str, CodeEntry]
    source: str = ""  # passage id
    evidence: list[Evidence] = Field(default_factory=list)
    status: Confidence = "confirmed"


# ─── knowledge layer ─────────────────────────────────────────────────────────────────────────────

class KnowledgePassage(BaseModel):
    """A quotable chunk of the brief, a regulation, or an operator's own words. Briefings cite these by id."""

    id: str
    doc: str
    title: str
    text: str
    kind: Literal["brief", "regulation", "standard", "statistic", "definition", "operator"] = "brief"
    url: str = ""
    retrieved: str = ""  # YYYY-MM-DD
    domain: Domain = "shared"
    by: str = ""  # operator passages: who said it (an Operator.id)


# ─── elicitation layer: what the documents could not say, asked of the people who know ─────────

class Operator(BaseModel):
    """A named person whose knowledge is in the model. Judges want a named user; here they are."""

    id: str  # duty_mgr_ord
    name: str
    role: Domain  # which agent's domain they speak for
    title: str = ""  # "Duty manager, ORD", "B737 captain", "Ramp supervisor"
    organisation: str = ""
    # `example`: a persona written to exercise the stage; every passage they "say" is labelled so.
    # `interviewed`: a real person's words. Only these should ever be presented as operator grounding.
    status: Literal["example", "interviewed"] = "example"


class Question(BaseModel):
    """One thing the build could not learn from documents. Generated, not hand-written."""

    id: str  # q.ground.turnaround
    role: Domain
    kind: Literal["synthetic_type", "default_param", "undescribed_concept", "unsourced_metric",
                  "unsourced_rule", "open"]
    target_kind: Literal["type", "rule", "concept", "metric", "none"]
    target: str
    text: str
    why: str = ""  # what the model currently assumes and where that came from
    priority: int = 2  # 1 changes feasibility, 2 changes ranking, 3 changes wording


class Answer(BaseModel):
    """An operator's answer, as given. Never edited; a later answer to the same question supersedes it."""

    question_id: str
    by: str  # Operator.id
    at: str  # ISO timestamp
    text: str  # their words, verbatim
    action: Literal["answer", "confirm_default", "skip", "not_applicable"] = "answer"
    # Structured reading of the answer, proposed by the interpreter and confirmed by the operator.
    # Exactly the fields a Rule / Metric / Concept update needs; None until confirmed.
    structured: Optional[dict[str, Any]] = None
    confirmed: bool = False
    via: Literal["cli", "api", "panel", "chat"] = "cli"


class Elicitation(BaseModel):
    operators: list[Operator] = Field(default_factory=list)
    questions: list[Question] = Field(default_factory=list)
    answers: list[Answer] = Field(default_factory=list)  # append-only ledger


class KnowledgeLink(BaseModel):
    passage_id: str
    target_kind: Literal["concept", "type", "rule", "metric", "code_set"]
    target: str
    kind: Literal["defines", "constrains", "describes", "sources"] = "describes"


class VocabTerm(BaseModel):
    """What people say → what the model calls it."""

    term: str
    target_kind: Literal["concept", "type", "metric", "rule", "code"]
    target: str
    source: str = "user"


class Project(BaseModel):
    id: str
    name: str
    description: str = ""
    challenge: str = ""
    timezone: str = "UTC"


class SemanticModel(BaseModel):
    version: int = 1
    project: Project
    tables: list[Table] = Field(default_factory=list)
    concepts: list[Concept] = Field(default_factory=list)
    entity_types: list[EntityType] = Field(default_factory=list)
    relation_types: list[RelationType] = Field(default_factory=list)
    metrics: list[Metric] = Field(default_factory=list)
    rules: list[Rule] = Field(default_factory=list)
    code_sets: list[CodeSet] = Field(default_factory=list)
    passages: list[KnowledgePassage] = Field(default_factory=list)
    knowledge_links: list[KnowledgeLink] = Field(default_factory=list)
    vocabulary: list[VocabTerm] = Field(default_factory=list)
    elicitation: Elicitation = Field(default_factory=Elicitation)

    # ── loading ──

    @classmethod
    def load(cls, directory: Path = SEMANTIC_DIR, apply_operator_knowledge: bool = True) -> "SemanticModel":
        """model.yaml (curated) + schema.yaml (generated) + elicitation.yaml (operator ledger) → one model.

        Operator answers are applied on load, so everything downstream (rules.py, briefs, the viewer)
        sees one model. The ledger itself is never mutated by loading.
        """
        curated = yaml.safe_load((directory / "model.yaml").read_text()) or {}
        schema_path = directory / "schema.yaml"
        if schema_path.exists():
            curated["tables"] = (yaml.safe_load(schema_path.read_text()) or {}).get("tables", [])
        elic_path = directory / "elicitation.yaml"
        if elic_path.exists():
            curated["elicitation"] = yaml.safe_load(elic_path.read_text()) or {}
        m = cls.model_validate(curated)
        if apply_operator_knowledge and m.elicitation.answers:
            from .elicit import apply_answers
            apply_answers(m)
        return m

    # ── integrity ──

    def validate_references(self) -> list[str]:
        """Dangling references are errors: an agent must never be briefed on a rule that cites nothing."""
        problems: list[str] = []
        concepts = {c.name for c in self.concepts}
        types = {t.name for t in self.entity_types}
        metrics = {m.name for m in self.metrics}
        rules = {r.id for r in self.rules}
        codes = {c.name for c in self.code_sets}
        passages = {p.id for p in self.passages}
        columns = {f"{t.name}.{c.name}" for t in self.tables for c in t.columns}

        for c in self.concepts:
            if c.extends and c.extends not in concepts:
                problems.append(f"concept {c.name} extends unknown {c.extends}")
        for t in self.entity_types:
            if t.concept not in concepts:
                problems.append(f"type {t.name} has unknown concept {t.concept}")
            if t.table and self.tables:
                for col in [t.id_column, t.name_column, *t.attribute_columns]:
                    if col and f"{t.table}.{col}" not in columns:
                        problems.append(f"type {t.name} binds missing column {t.table}.{col}")
        for r in self.relation_types:
            for side in (r.source_type, r.target_type):
                if side not in types:
                    problems.append(f"relation {r.name} references unknown type {side}")
        for r in self.rules:
            if r.source and r.source not in passages:
                problems.append(f"rule {r.id} cites unknown passage {r.source}")
            for s in r.subjects:
                if s not in types and s not in metrics and s not in codes:
                    problems.append(f"rule {r.id} subject {s!r} is not a type, metric or code set")
        for cs in self.code_sets:
            if cs.source and cs.source not in passages:
                problems.append(f"code set {cs.name} cites unknown passage {cs.source}")
        for k in self.knowledge_links:
            if k.passage_id not in passages:
                problems.append(f"link to unknown passage {k.passage_id}")
            pool = {"concept": concepts, "type": types, "rule": rules, "metric": metrics, "code_set": codes}[k.target_kind]
            if k.target not in pool:
                problems.append(f"link {k.passage_id} -> unknown {k.target_kind} {k.target}")
        return problems
