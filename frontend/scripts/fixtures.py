"""Run from repo root: uv run python frontend/scripts/fixtures.py. No LLM/API calls."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root))
from atc_negotiation.agents import make_agents
from atc_negotiation.orchestrator import negotiate
from atc_negotiation.schemas import Scenario

fixtures = {}
for name, file, turns in [
    ("consensus", "sample_weather.json", 3),
    ("fallback", "sample_weather.json", 1),
    ("no_legal_option", "sample_no_legal_option.json", 3),
]:
    scenario = Scenario.model_validate_json((root / "scenarios" / file).read_text())
    trace = negotiate(scenario, make_agents(mock=True), max_turns=turns)
    assert trace.outcome == name
    data = trace.model_dump(mode="json")
    data["started_at"] = "2026-10-31T00:00:00Z"
    data["duration_s"] = 0
    fixtures[name] = data
(root / "frontend/src/preview/traces.ts").write_text(
    "// Generated by scripts/fixtures.py from the backend mock agents.\n"
    "import type { Trace } from '@/workspace';\n"
    "const traces: Record<Trace['outcome'], Trace> = " + json.dumps(fixtures, indent=2) + ";\nexport default traces;\n"
)
